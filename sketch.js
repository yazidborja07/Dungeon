let jugador;

let size = 0;

let input;

let map = mapa.dungeon2;
console.log(map);

let playerImage;

function preload() {
  playerImage = loadImage("/assets/skeleton.png");
}

function setup() {
  let cuadro = createCanvas(650, 650);
  cuadro.center(0);

  Input.init();

  background(100);

  size = width / map.length;

  noSmooth();

  jugador = new Jugador(size, playerImage);
}

function dibujarMapa() {
  for (let y = 0; y < map.length; y++) {
    for (let x = 0; x < map[y].length; x++) {
      const cell = map[y][x];

      stroke("white");

      if (cell == 1) {
        fill("gray");
      } else if (cell == 5) {
        fill("dodgerblue");
      } else {
        fill("black");
      }

      rect(x * size, y * size, size, size);
    }
  }
}

function draw() {
  dibujarMapa();

  jugador.update();
  jugador.draw();
}
