let jugador;

let fantasmas = [];

let size = 0;

let input;

let map = mapa.dungeon2;
console.log(map);

let playerImage;
let ghostImage;

function preload() {
  playerImage = loadImage("/assets/skeleton.png");
  ghostImage = loadImage("/assets/fantasma.png");
}

function setup() {
  let cuadro = createCanvas(650, 650);
  cuadro.center(0);

  Input.init();

  background(100);

  size = width / map.length;

  noSmooth();

  jugador = new Jugador(size, playerImage);

  for (let i = 0; i < 3; i++) {
    fantasmas.push(new Ghost(10 + 2, 10 - 1, size, ghostImage));
  }
}

function dibujarMapa() {
  for (let y = 0; y < map.length; y++) {
    for (let x = 0; x < map[y].length; x++) {
      const cell = map[y][x];

      stroke("white");

      if (cell == 1) {
        fill("gray");
      } else if (cell == 5) {
        fill("dodgerblue");
      } else {
        fill("black");
      }

      rect(x * size, y * size, size, size);
    }
  }
}

function draw() {
  dibujarMapa();

  for (let i = 0; i < fantasmas.length; i++) {
    let gasparin = fantasmas[i];
    gasparin.draw();
    gasparin.update();
  }

  jugador.update();
  jugador.draw();
}
